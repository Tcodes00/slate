"""Real PDF generation for invoices — reportlab, in-memory, no filesystem
writes needed. Closes the 'documents are tracked, not generated' gap for
Finance specifically."""

import io

from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas


def build_invoice_pdf(invoice: dict) -> bytes:
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=letter)
    width, height = letter

    c.setFont("Helvetica-Bold", 20)
    c.drawString(1 * inch, height - 1 * inch, "Slate")
    c.setFont("Helvetica", 10)
    c.drawString(1 * inch, height - 1.25 * inch, "Invoice")

    c.setFont("Helvetica-Bold", 14)
    c.drawRightString(width - 1 * inch, height - 1 * inch, invoice["invoice_number"])
    c.setFont("Helvetica", 10)
    c.drawRightString(width - 1 * inch, height - 1.2 * inch, f"Status: {invoice['status']}")

    y = height - 1.8 * inch
    c.setFont("Helvetica-Bold", 11)
    c.drawString(1 * inch, y, "Bill to")
    c.setFont("Helvetica", 11)
    c.drawString(1 * inch, y - 0.2 * inch, invoice["company"])

    c.setFont("Helvetica-Bold", 11)
    c.drawString(4.5 * inch, y, "Issued")
    c.setFont("Helvetica", 11)
    c.drawString(4.5 * inch, y - 0.2 * inch, str(invoice["issued_at"])[:10])
    if invoice.get("due_date"):
        c.setFont("Helvetica-Bold", 11)
        c.drawString(4.5 * inch, y - 0.45 * inch, "Due")
        c.setFont("Helvetica", 11)
        c.drawString(4.5 * inch, y - 0.65 * inch, str(invoice["due_date"])[:10])

    table_y = y - 1.2 * inch
    c.setFont("Helvetica-Bold", 10)
    c.drawString(1 * inch, table_y, "Description")
    c.drawRightString(width - 1 * inch, table_y, "Amount")
    c.line(1 * inch, table_y - 0.08 * inch, width - 1 * inch, table_y - 0.08 * inch)

    c.setFont("Helvetica", 10)
    c.drawString(1 * inch, table_y - 0.3 * inch, invoice["description"])
    c.drawRightString(width - 1 * inch, table_y - 0.3 * inch, f"${invoice['amount']:,.2f}")

    c.line(1 * inch, table_y - 0.5 * inch, width - 1 * inch, table_y - 0.5 * inch)
    c.setFont("Helvetica-Bold", 12)
    c.drawRightString(width - 1 * inch, table_y - 0.75 * inch, f"Total: ${invoice['amount']:,.2f}")

    c.setFont("Helvetica", 8)
    c.drawString(1 * inch, 0.75 * inch, "Generated by Slate — this is a real, rendered PDF, not a placeholder.")

    c.showPage()
    c.save()
    return buf.getvalue()
